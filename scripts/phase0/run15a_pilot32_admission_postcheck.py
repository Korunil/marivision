def risk_for_task(out, O, expert, task, policy):
    if task == 'box':
        return risk_admission(out['box_channels'][expert], 'box', policy)
    channels = dict(out['cls_channels'][expert])
    posterior = out['cls_raw'][expert]
    high = O.z.sigmoid() >= .20
    loss = ((posterior[...,1] + posterior[...,2]) * high).amax(-1,keepdim=True)
    added = posterior[...,7].amax(-1,keepdim=True)
    channels['p_loss'] = torch.maximum(channels['p_loss'],loss)
    channels['p_add'] = torch.maximum(channels['p_add'],added)
    return risk_admission(channels, 'cls', policy)


def percentile(vals, frac):
    if not vals: return None
    a = sorted(vals)
    i = (len(a)-1)*frac
    lo=int(math.floor(i));hi=int(math.ceil(i))
    return float(a[lo]*(hi-i)+a[hi]*(i-lo)) if hi!=lo else float(a[lo])


def inspect(project, videos, frame_limit, checkpoint_name):
    project=Path(project).resolve()
    for filename,digest in EXPECTED_SOURCES.items():
        require(sha(project/filename)==digest, 'Installed source version not audited: '+filename)
    ckpt=project/'bfcef_f_s0'/'run15a_final_candidate_sandbox'/'pilot_fit'/checkpoint_name
    receipt=ckpt.with_suffix('.receipt.json')
    require(ckpt.is_file() and receipt.is_file(),'Pilot checkpoint/receipt missing')
    require(sha(ckpt)==EXPECTED_CHECKPOINT,'Pilot checkpoint SHA differs from uploaded receipt')
    rec=json.loads(receipt.read_text(encoding='utf-8'))
    require(rec['checkpoint_sha256']==EXPECTED_CHECKPOINT and rec['frames']==32,'Unexpected pilot receipt')
    require(tuple(videos) and all(v in FIT for v in videos),'Only permitted FIT videos')
    require(1<=frame_limit<=64,'Frame limit must be 1..64')
    old,r9,r8,d,s0a,raw,_,_,_=load_runtime(project,downstream='none')
    r12=old.imports_and_verify()[1]
    model,criterion,CO,FX=old.make_model(r9,r12)
    # Checkpoint is generated by this project, not downloaded from untrusted third parties.
    payload=torch.load(ckpt,map_location='cpu',weights_only=False)
    require(payload.get('checkpoint_type')=='PILOT_ONLY_NOT_CALIBRATED','Unexpected checkpoint type')
    require(tuple(payload.get('video_ids',()))==(2,3) and payload.get('max_frames_per_video')==16,'Unexpected pilot split')
    require(payload.get('source_sha256')==EXPECTED_SOURCES['run15a_final_pilot_fit.py'],'Pilot driver source mismatch')
    old.restore_downstream(model,payload['downstream_state'])
    old.lock_gate_thresholds(model)
    old.verify_gate_thresholds(model,'RUN15A pilot postcheck')
    model.eval()
    policy=RiskPolicy()
    gates={}
    hooks=[]
    def make_hook(task,expert):
        def hook(_module, _inputs, outputs):
            gates[(task,expert)]={k:v.detach() for k,v in outputs.items() if k in ('mask_hard','g_soft')}
        return hook
    for task in ('cls','box'):
        for e in EXPERTS:
            hooks.append(getattr(model,'gate_'+task)[e].register_forward_hook(make_hook(task,e)))
    counts=collections.defaultdict(collections.Counter)
    values=collections.defaultdict(list)
    videos_summary={}
    nframes=0
    try:
        with torch.no_grad():
            for vid in videos:
                can,spa,tmp=s0a.load_video_triplet(vid)
                vc=collections.Counter()
                for j in range(min(frame_limit,len(can))):
                    gates.clear()
                    fr=can[j]
                    O,X=s0a.make_O_X(fr,spa[j],tmp[j],CO,FX)
                    bundle=r9.expert_bundle(model,O,X)
                    out=mechanism_forward(model,O,X,bundle,hard=True,policy=policy)
                    mm0,fp0,_=old.capture_match(O.z,O.b,fr['gt_boxes_norm'],fr['gt_labels'])
                    mm1,fp1,_=old.capture_match(out['z'],out['b'],fr['gt_boxes_norm'],fr['gt_labels'])
                    ledger=identity_ledger(mm0,mm1)
                    vc.update({'frames':1,'baseline_tp':len(mm0),'candidate_tp':len(mm1),
                               'baseline_fp':len(fp0),'candidate_fp':len(fp1),
                               'lost':len(ledger['lost']),'rescued':len(ledger['rescued'])})
                    for task in ('cls','box'):
                        for k,e in enumerate(EXPERTS):
                            src=gates[(task,e)]
                            tsk=src['mask_hard'].reshape(-1).bool()
                            risk=risk_for_task(out,O,e,task,policy)
                            rk=risk['mask_hard'].reshape(-1).bool()
                            avail=out['A_'+task][:,k].reshape(-1).bool()
                            hard=out['hard_'+task][:,k].reshape(-1).bool()
                            require(torch.equal(hard,tsk & rk & avail),
                                    f'Admission decomposition mismatch for {vid}/{j}/{task}/{e}')
                            key=f'{task}_{e}'
                            a=int(avail.sum().item())
                            counts[key]['eligible']+=a
                            counts[key]['tsk_open']+=int((tsk & avail).sum().item())
                            counts[key]['risk_open']+=int((rk & avail).sum().item())
                            counts[key]['joint_open']+=int((hard & avail).sum().item())
                            counts[key]['tsk_only']+=int((tsk & ~rk & avail).sum().item())
                            counts[key]['risk_only']+=int((~tsk & rk & avail).sum().item())
                            counts[key]['both_closed']+=int((~tsk & ~rk & avail).sum().item())
                            if a:
                                values[key+'_tsk'].extend(src['g_soft'].reshape(-1)[avail].float().cpu().tolist())
                                values[key+'_risk'].extend(risk['score'].reshape(-1)[avail].float().cpu().tolist())
                    nframes+=1
                videos_summary[str(vid)]=dict(vc)
                print(f'[POSTCHECK] FIT video={vid}: frames={vc["frames"]} lost={vc["lost"]} rescued={vc["rescued"]}',flush=True)
    finally:
        for hook in hooks:hook.remove()
    summary={}
    for key,c in sorted(counts.items()):
        n=c['eligible']; require(n>0,'Zero-eligible audit group: '+key)
        sg=values[key+'_tsk'];sr=values[key+'_risk']
        summary[key]={**dict(c),'tsk_open_rate':c['tsk_open']/n,
                      'risk_open_rate':c['risk_open']/n,'joint_open_rate':c['joint_open']/n,
                      'tsk_gsoft_p05_p50_p95':[percentile(sg,f) for f in (.05,.50,.95)],
                      'risk_score_p05_p50_p95':[percentile(sr,f) for f in (.05,.50,.95)]}
    return {'schema':'RUN15A_PILOT32_ADMISSION_POSTCHECK_v1',
            'status':'FIT_DIAGNOSTIC_ONLY_NOT_QUALIFIED',
            'trained_checkpoint_sha256':EXPECTED_CHECKPOINT,
            'pilot_train_videos':[2,3],
            'diagnostic_videos':videos,
            'first_frames_per_video':frame_limit,
            'frames':nframes,'per_video':videos_summary,
            'admission':summary,'all_hard_gates_closed':all(c['joint_open']==0 for c in counts.values()),
            'no_training_or_optimizer':True,'CAL_QUAL_Val_Test_unopened':True,
            'limitations':['The probe uses an already exposed FIT set; held-out downstream pilot videos are not independent upstream detector tests',
                           'TSK and risk scores are uncalibrated; threshold changes are forbidden in this diagnostic',
                           'F1/TP on the sampled operating threshold is not mAP; this audit makes no AP claim']}


def selftest():
    vals=[0.,1.,3.,8.]
    assert [percentile(vals,p) for p in (0.,.5,1.)]==[0.,2.,8.]
    p=RiskPolicy()
    ch={k:torch.tensor([[v]],dtype=torch.float32) for k,v in {'U':.8,'H':.1,'sigma':.1,'p_loss':.1}.items()}
    r=risk_admission(ch,'box',p)
    assert float(r['mask_hard'][0,0])==1.
    print('[PASS] postcheck elementary selftest')


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--project',default=r'D:\MARIVISION\H0_workbench\eval_tools')
    parser.add_argument('--videos',default='2,3,4')
    parser.add_argument('--frames',type=int,default=16)
    parser.add_argument('--checkpoint',default='pilot_videos_2_3_frames16.pth')
    parser.add_argument('--selftest',action='store_true')
    args=parser.parse_args()
    if args.selftest:selftest();return
    videos=tuple(int(x) for x in args.videos.split(','))
    require(len(videos)==len(set(videos)) and 1<=len(videos)<=4,'Unique 1..4 FIT videos')
    result=inspect(args.project,videos,args.frames,args.checkpoint)
    out=Path(args.project)/'bfcef_f_s0'/'run15a_final_candidate_sandbox'/'pilot_postcheck'
    name=f'pilot32_gate_postcheck_videos_{"_".join(map(str,videos))}_frames{args.frames}.json'
    path=out/name
    write_new(path,result)
    print('[POSTCHECK COMPLETE]',path,flush=True)
    for e in EXPERTS:
        for task in ('cls','box'):
            k=f'{task}_{e}';c=result['admission'][k]
            print(f'  {k}: tsk_open={c["tsk_open_rate"]:.3f} risk_open={c["risk_open_rate"]:.3f} joint_open={c["joint_open_rate"]:.3f} '
                  f'tsk_gsoft_p50={c["tsk_gsoft_p05_p50_p95"][1]:.5f} risk_margin_p50={c["risk_score_p05_p50_p95"][1]:.5f}')
    print('[LIMIT] FIT-only analysis, no new training or AP claim')
if __name__=='__main__':main()
